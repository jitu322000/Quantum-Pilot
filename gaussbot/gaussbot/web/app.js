function renderGenecpElements() {
  if (el("basis").value !== "__genecp__") return;
  const container = el("genecp-elements");
  const elements = unionElements();
  if (elements.length === 0) {
    container.innerHTML = '<p class="hint" style="margin:0">Upload a structure above to list its elements here.</p>';
    return;
  }
  container.innerHTML = "";
  elements.forEach((symbol) => {
    const wrap = document.createElement("div");
    wrap.className = "genecp-element";
    wrap.innerHTML = `
      <label class="el-header">
        <input type="checkbox" class="ecp-check" data-el="${symbol}"> ${symbol}
      </label>
      <input type="text" class="ecp-name hidden" data-el="${symbol}" placeholder="e.g. LanL2DZ" value="LanL2DZ">
    `;
    container.appendChild(wrap);
    const checkbox = wrap.querySelector(".ecp-check");
    const nameInput = wrap.querySelector(".ecp-name");
    checkbox.addEventListener("change", () => nameInput.classList.toggle("hidden", !checkbox.checked));
  });
}

