// ---------------------------------------------------------------- studies
//
// Every submitted job gets its own card (newest first) with independent
// polling, so several studies can run side by side -- the form itself
// only ever starts one job at a time, but nothing stops the user from
// reopening it (via "+ Start another study") and submitting another
// while earlier ones are still going.

const TRASH_ICON = `<svg viewBox="0 0 16 16" width="14" height="14" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round"><path d="M2 4h12M5.5 4V2.5A1 1 0 0 1 6.5 1.5h3A1 1 0 0 1 10.5 2.5V4M6.5 7.5v4.5M9.5 7.5v4.5M3.5 4l.6 8.4A1 1 0 0 0 5.1 13.4h5.8a1 1 0 0 0 1-1.1L13 4"/></svg>`;

function addStudyCard(jobId, jobName) {
  const list = el("studies-list");
  const card = document.createElement("div");
  card.className = "study-card";
  card.dataset.jobId = jobId;
  card.innerHTML = `
    <div class="study-card-header">
      <span class="study-name">${jobName}</span>
      <div class="study-card-actions">
        <button type="button" class="stop-btn small-btn">Stop</button>
        <span class="badge running">Running</span>
        <button type="button" class="delete-btn" title="Remove this study entry" disabled>${TRASH_ICON}</button>
      </div>
    </div>
    <p class="stage-text"></p>
    <details class="study-log-details">
      <summary>Log</summary>
      <pre class="log-panel"></pre>
    </details>
    <div class="study-results"></div>
  `;
  list.prepend(card);
  el("studies-panel").classList.remove("hidden");

  const deleteBtn = card.querySelector(".delete-btn");
  deleteBtn.addEventListener("click", async () => {
    deleteBtn.disabled = true;
    try {
      const res = await fetch(`/api/jobs/${jobId}`, { method: "DELETE" });
      if (!res.ok) {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.detail || `HTTP ${res.status}`);
      }
      card.remove();
      if (!list.children.length) {
        // Nothing left in the Studies list -- if the form is also
        // hidden (the normal state right after submitting a study),
        // there'd be no visible way back to it, since "+ Start
        // another study" lives inside this panel. Show the form
        // instead of just hiding an empty panel.
        el("studies-panel").classList.add("hidden");
        el("job-form").classList.remove("hidden");
      }
    } catch (e) {
      deleteBtn.disabled = false;
      deleteBtn.title = `Couldn't remove: ${e.message}`;
    }
  });

  const stopBtn = card.querySelector(".stop-btn");
  stopBtn.addEventListener("click", async () => {
    stopBtn.disabled = true;
    stopBtn.textContent = "Stopping...";
    try {
      await fetch(`/api/jobs/${jobId}/cancel`, { method: "POST" });
    } catch (e) {
      stopBtn.disabled = false;
      stopBtn.textContent = "Stop";
    }
  });

  pollStudy(jobId, jobName, card);
}

function pollStudy(jobId, jobName, card) {
  const badge = card.querySelector(".badge");
  const stopBtn = card.querySelector(".stop-btn");
  const deleteBtn = card.querySelector(".delete-btn");
  const stageText = card.querySelector(".stage-text");
  const logPanel = card.querySelector(".log-panel");
  const resultsDiv = card.querySelector(".study-results");

  const poll = async () => {
    let data;
    try {
      const res = await fetch(`/api/jobs/${jobId}`);
      data = await res.json();
    } catch (e) {
      stageText.textContent = "Lost contact with the server -- is it still running?";
      setTimeout(poll, 3000);
      return;
    }

    stageText.textContent = data.stage || "";
    logPanel.textContent = (data.log || []).join("\n");

    if (data.status === "running") {
      setTimeout(poll, 1500);
    } else if (data.status === "done") {
      stopBtn.remove();
      deleteBtn.disabled = false;
      badge.textContent = "Done";
      badge.className = "badge good";
      renderStudyResults(resultsDiv, data.result);
    } else if (data.status === "cancelled") {
      stopBtn.remove();
      deleteBtn.disabled = false;
      badge.textContent = "Cancelled";
      badge.className = "badge cancelled";
      const restartBtn = document.createElement("button");
      restartBtn.type = "button";
      restartBtn.className = "small-btn";
      restartBtn.textContent = "Restart";
      restartBtn.addEventListener("click", async () => {
        restartBtn.disabled = true;
        restartBtn.textContent = "Restarting...";
        try {
          const res = await fetch(`/api/jobs/${jobId}/restart`, { method: "POST" });
          if (!res.ok) {
            const body = await res.json().catch(() => ({}));
            throw new Error(body.detail || `HTTP ${res.status}`);
          }
          const { job_id } = await res.json();
          addStudyCard(job_id, jobName);
        } catch (e) {
          restartBtn.disabled = false;
          restartBtn.textContent = "Restart";
          resultsDiv.innerHTML = `<p class="error">Couldn't restart: ${e.message}</p>`;
        }
      });
      resultsDiv.innerHTML = "";
      resultsDiv.appendChild(restartBtn);
    } else {
      stopBtn.remove();
      deleteBtn.disabled = false;
      badge.textContent = "Failed";
      badge.className = "badge bad";
      resultsDiv.innerHTML = `<p class="error">${data.error || "The job failed."}</p>`;
    }
  };
  poll();
}

function row(label, value) {
  return `<div class="result-row"><span class="label">${label}</span><span class="value">${value}</span></div>`;
}


function renderReactionCoordinatePlot(result) {
  const units = result.energy_units || [];
  const unit = units.includes("kcal/mol") ? "kcal/mol" : units[0];
  if (!unit || !result.energies || !result.energies[unit]) return "";
  const e = result.energies[unit];
  const points = [
    { label: "Reactant", x: 0, y: 0 },
    { label: "TS", x: 0.5, y: e.ts },
    { label: "Product", x: 1, y: e.product },
  ];

  const width = 360, height = 190, padTop = 50, padBottom = 34, padX = 44;
  const plotW = width - 2 * padX, plotH = height - padTop - padBottom;
  const yMin = Math.min(0, ...points.map((p) => p.y));
  const yMax = Math.max(0, ...points.map((p) => p.y));
  const yRange = yMax - yMin || 1;

  const toXY = (p) => [padX + p.x * plotW, padTop + ((yMax - p.y) / yRange) * plotH];
  const [x0, y0] = toXY(points[0]);
  const [x1, y1] = toXY(points[1]);
  const [x2, y2] = toXY(points[2]);
  const mid1x = (x0 + x1) / 2, mid2x = (x1 + x2) / 2;
  const path = `M ${x0} ${y0} C ${mid1x} ${y0}, ${mid1x} ${y1}, ${x1} ${y1} C ${mid2x} ${y1}, ${mid2x} ${y2}, ${x2} ${y2}`;
  const digits = unit === "Hartree" ? 5 : 2;

  const markers = points
    .map((p) => {
      const [px, py] = toXY(p);
      return `<circle cx="${px}" cy="${py}" r="4" class="plot-point"></circle>
        <text x="${px}" y="${py - 10}" class="plot-value" text-anchor="middle">${p.y.toFixed(digits)}</text>
        <text x="${px}" y="${padTop + plotH + 18}" class="plot-label" text-anchor="middle">${p.label}</text>`;
    })
    .join("");

  return `
    <div class="reaction-plot">
      <button type="button" class="print-plot-btn" title="Print this plot">${PRINT_ICON}</button>
      <svg viewBox="0 0 ${width} ${height}" class="reaction-plot-svg">
        <text x="${padX}" y="14" class="plot-title">Reaction coordinate (${unit})</text>
        <line x1="${padX}" y1="${padTop + plotH}" x2="${width - padX}" y2="${padTop + plotH}" class="plot-axis"></line>
        <path d="${path}" class="plot-curve" fill="none"></path>
        ${markers}
      </svg>
    </div>
  `;
}

const PRINT_ICON = `<svg viewBox="0 0 16 16" width="14" height="14" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round"><path d="M4 5.5V1.5h8v4M4 11.5h-2a1 1 0 0 1-1-1v-3a1 1 0 0 1 1-1h12a1 1 0 0 1 1 1v3a1 1 0 0 1-1 1h-2M4 9h8v5.5H4z"/></svg>`;

function wirePrintButtons(container) {
  container.querySelectorAll(".print-plot-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const svg = btn.closest(".reaction-plot").querySelector(".reaction-plot-svg");
      if (!svg) return;
      const win = window.open("", "_blank", "width=500,height=420");
      if (!win) return;
      win.document.write(`
        <!doctype html>
        <html><head><title>Reaction coordinate</title>
        <style>
          body { margin: 0; padding: 24px; background: #fff; color: #000; font-family: sans-serif; }
          svg { width: 100%; height: auto; }
          svg text { fill: #000; }
          svg .plot-curve { stroke: #000; }
          svg .plot-axis { stroke: #666; }
          svg .plot-point { fill: #000; }
        </style>
        </head><body>${svg.outerHTML}</body></html>
      `);
      win.document.close();
      win.onload = () => win.print();
    });
  });
}

function digitsFor(unit) {
  return unit === "Hartree" ? 5 : 2;
}

function renderResultsTables(compounds, units, result) {
  const hasGcorr = result.g_corr && Object.keys(result.g_corr).length > 0;
  const hasXyz = result.xyz_files && Object.keys(result.xyz_files).length > 0;
  const hasCdxml = result.cdxml_files && Object.keys(result.cdxml_files).length > 0;

  let energyHead = "<th>Sr No</th><th>Compound</th>";
  units.forEach((u) => (energyHead += `<th>Energy (${u})</th>`));
  if (hasGcorr) units.forEach((u) => (energyHead += `<th>G-corr (${u})</th>`));

  let energyBody = "";
  compounds.forEach((c) => {
    energyBody += `<tr><td>${c.no}</td><td>${c.label}</td>`;
    units.forEach((u) => {
      const v = c.energy(u);
      energyBody += `<td>${v == null ? "n/a" : v.toFixed(digitsFor(u))}</td>`;
    });
    if (hasGcorr) {
      units.forEach((u) => {
        const gc = result.g_corr[c.key];
        energyBody += `<td>${gc && gc[u] != null ? gc[u].toFixed(digitsFor(u)) : "n/a"}</td>`;
      });
    }
    energyBody += "</tr>";
  });

  let filesHead = "<th>Sr No</th><th>Compound</th><th>Logs</th>";
  if (hasXyz) filesHead += "<th>XYZ</th>";
  if (hasCdxml) filesHead += "<th>CDXML</th>";

  let filesBody = "";
  compounds.forEach((c) => {
    const logPath = (result.log_files || {})[c.key];
    filesBody += `<tr><td>${c.no}</td><td>${c.label}</td><td>${logPath || "n/a"}</td>`;
    if (hasXyz) {
      const xyzPath = (result.xyz_files || {})[c.key];
      filesBody += `<td>${xyzPath || "n/a"}</td>`;
    }
    if (hasCdxml) {
      const cdxmlPath = (result.cdxml_files || {})[c.key];
      filesBody += `<td>${cdxmlPath || "n/a"}</td>`;
    }
    filesBody += "</tr>";
  });

  return `
    <div class="results-tables">
      <div class="results-table-wrap"><table class="results-table"><thead><tr>${energyHead}</tr></thead><tbody>${energyBody}</tbody></table></div>
      <div class="results-table-wrap"><table class="results-table"><thead><tr>${filesHead}</tr></thead><tbody>${filesBody}</tbody></table></div>
    </div>
  `;
}

function renderStudyResults(content, result) {
  if (!result) {
    content.innerHTML = "<p>No result data.</p>";
    return;
  }

  if (result.type === "single") {
    const compounds = [{ no: 1, label: "Structure", key: "final", energy: () => result.zpe_energy ?? result.scf_energy }];
    content.innerHTML =
      row("Job", result.job_name) +
      `<div class="results-layout">` +
      renderResultsTables(compounds, ["Hartree"], result) +
      `</div>` +
      row("Files", result.out_dir);
    return;
  }

  if (result.type === "ts_search") {
    const overlapRow = result.match_overlap != null
      ? row("TS/reaction overlap", result.match_overlap.toFixed(2))
      : row("TS/reaction overlap", "n/a (no reactant/product given to check against)");

    let recoveryRows = "";
    const rec = result.recovery;
    if (rec) {
      if (rec.classified) {
        recoveryRows += row("Recovered reactant", rec.reactant_log || "not recovered");
        recoveryRows += row("Recovered product", rec.product_log || "not recovered");
      } else {
        recoveryRows += row("Recovered side A", `${rec.side_a_log || "not recovered"} (reactant or product -- not determined which)`);
        recoveryRows += row("Recovered side B", `${rec.side_b_log || "not recovered"} (reactant or product -- not determined which)`);
      }
    }

    const hasXyz = result.xyz_files && Object.keys(result.xyz_files).length > 0;
    const hasCdxml = result.cdxml_files && Object.keys(result.cdxml_files).length > 0;
    // Only present once there's a usable reactant AND product -- either
    // given directly to the TS search and independently optimized, or
    // recovered from the TS -- letting this section show the same
    // reaction-coordinate report the mechanism study does, per your
    // request to be able to extract that data here too.
    const hasReactionCoordinate = result.energies && Object.keys(result.energies).length > 0;

    const sourceLabel = { ts_distortion: "recovered from the TS (distortion + reopt)" };
    let sourceRows = "";
    if (hasReactionCoordinate) {
      if (result.reactant_source && result.reactant_source !== "guess") {
        sourceRows += row("Reactant source", sourceLabel[result.reactant_source] || result.reactant_source);
      }
      if (result.product_source && result.product_source !== "guess") {
        sourceRows += row("Product source", sourceLabel[result.product_source] || result.product_source);
      }
    }

    content.innerHTML =
      row("Job", result.job_name) +
      row("TS found", '<span class="badge good">yes</span>') +
      row("Imaginary freq", `${result.imaginary_freq.toFixed(1)} cm⁻¹`) +
      overlapRow +
      row("TS log", (result.log_files || {}).ts || "n/a") +
      (hasXyz && !hasReactionCoordinate ? row("TS XYZ", (result.xyz_files || {}).ts || "n/a") : "") +
      (hasCdxml && !hasReactionCoordinate ? row("TS CDXML", (result.cdxml_files || {}).ts || "n/a") : "") +
      recoveryRows +
      sourceRows +
      (hasReactionCoordinate
        ? `<div class="results-layout">${renderResultsTables(
            [
              { no: 1, label: "Reactant", key: "reactant", energy: () => 0 },
              { no: 2, label: "TS", key: "ts", energy: (u) => result.energies[u].ts },
              { no: 3, label: "Product", key: "product", energy: (u) => result.energies[u].product },
            ],
            result.energy_units || [],
            result
          )}${renderReactionCoordinatePlot(result)}</div>`
        : "") +
      row("Files", result.out_dir);
    if (hasReactionCoordinate) wirePrintButtons(content);
    return;
  }

  const ircBadge =
    result.irc_ran === false
      ? '<span class="badge">skipped</span>'
      : result.irc_connected
      ? '<span class="badge good">connected</span>'
      : '<span class="badge bad">needs review</span>';

  const sourceLabel = { guess: "original optimization", ts_distortion: "TS-mode distortion", irc_reopt: "IRC endpoint reopt" };
  let sourceRows = "";
  if (result.reactant_source && result.reactant_source !== "guess") {
    const why = result.reactant_recovered ? "recovered -- original optimization failed" : "more stable than the original optimization";
    sourceRows += row("Reactant source", `${sourceLabel[result.reactant_source] || result.reactant_source} (${why})`);
  }
  if (result.product_source && result.product_source !== "guess") {
    const why = result.product_recovered ? "recovered -- original optimization failed" : "more stable than the original optimization";
    sourceRows += row("Product source", `${sourceLabel[result.product_source] || result.product_source} (${why})`);
  }

  const units = result.energy_units || [];
  const compounds = [
    { no: 1, label: "Reactant", key: "reactant", energy: () => 0 },
    { no: 2, label: "TS", key: "ts", energy: (u) => result.energies[u].ts },
    { no: 3, label: "Product", key: "product", energy: (u) => result.energies[u].product },
  ];

  content.innerHTML =
    row("Job", result.job_name) +
    sourceRows +
    row("TS imaginary freq", `${result.ts_imaginary_freq.toFixed(1)} cm⁻¹`) +
    row("TS/reaction overlap", result.ts_match_overlap.toFixed(2)) +
    row("IRC", ircBadge) +
    `<div class="results-layout">` +
    renderResultsTables(compounds, units, result) +
    renderReactionCoordinatePlot(result) +
    `</div>` +
    row("Files", result.out_dir);
  wirePrintButtons(content);
}
