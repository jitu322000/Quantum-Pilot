function buildLevelRequest() {
  const method = el("method").value === "__custom__" ? el("method-custom").value.trim() : el("method").value;
  const basisSel = el("basis").value;

  if (basisSel === "__genecp__") {
    const ecp_assignments = {};
    document.querySelectorAll(".ecp-check").forEach((cb) => {
      if (cb.checked) {
        const symbol = cb.dataset.el;
        const nameInput = document.querySelector(`.ecp-name[data-el="${symbol}"]`);
        ecp_assignments[symbol] = (nameInput.value || "LanL2DZ").trim();
      }
    });
    return {
      method,
      basis: "",
      genecp: { ecp_assignments, light_basis: el("genecp-light-basis").value.trim() },
    };
  }

  const basis = basisSel === "__custom__" ? el("basis-custom").value.trim() : basisSel;
  return { method, basis };
}

