el("job-form").addEventListener("submit", async (evt) => {
  evt.preventDefault();
  showError("");

  const type = studyType();
  if (type === "mechanism" || type === "single") {
    if (!uploads.reactant) {
      showError(type === "mechanism" ? "Upload a reactant file first." : "Upload a structure file first.");
      return;
    }
  }
  if (type === "mechanism" && !uploads.product) {
    showError("Upload a product file first.");
    return;
  }
  if (type === "mechanism" && selectedEnergyUnits().length === 0) {
    showError("Pick at least one energy unit.");
    return;
  }
  if (type === "ts_search") {
    const hasGuess = !!uploads.ts_guess;
    const hasPair = !!uploads.reactant && !!uploads.product;
    if (!hasGuess && !hasPair) {
      showError("Provide a TS guess, or both a reactant and a product.");
      return;
    }
  }

  const req = {
    study_type: type,
    job_name: el("job-name").value.trim() || "job",
    reactant_token: uploads.reactant ? uploads.reactant.token : null,
    product_token: (type === "mechanism" || type === "ts_search") && uploads.product ? uploads.product.token : null,
    ts_guess_token: uploads.ts_guess ? uploads.ts_guess.token : null,
    reactant_id: el("reactant-id").value.trim() || null,
    product_id: el("product-id").value.trim() || null,
    nprocs: parseInt(el("nprocs").value, 10) || 2,
    mem_gb: parseInt(el("mem-gb").value, 10) || 2,
    max_repair_attempts: parseInt(el("max-repair-attempts").value, 10) || 4,
    level: buildLevelRequest(),
    run_irc: type === "mechanism" ? el("run-irc").checked : false,
    irc_points: parseInt(el("irc-points").value, 10) || 25,
    energy_units: type === "mechanism" ? selectedEnergyUnits() : ["kcal/mol"],
    run_ts_distortion: type === "mechanism" ? el("run-ts-distortion").checked : false,
    distortion_factor: parseFloat(el("distortion-factor").value) || 1.0,
    run_irc_endpoint_reopt: type === "mechanism" ? el("run-irc-endpoint-reopt").checked : false,
    recover_missing_endpoint: type === "mechanism" ? el("recover-missing-endpoint").checked : false,
    skip_pm6_preopt: el("skip-pm6-preopt").checked,
    ts_recover_endpoints: type === "ts_search" ? el("ts-recover-endpoints").checked : false,
    ts_use_calcall: type === "ts_search" ? el("ts-calcall-fallback").checked : false,
    export_xyz: el("export-xyz").checked,
    export_cdxml: el("export-cdxml").checked,
    compute_gcorr: type !== "ts_search" ? el("compute-gcorr").checked : false,
    gcorr_temperature: parseFloat(el("gcorr-temperature").value) || 298.15,
    gcorr_temperature_unit: el("gcorr-temperature-unit").value,
    executor: pbsEnabled ? "pbs" : "local",
    pbs_script_template: pbsEnabled ? el("pbs-script-textarea").value : null,
  };

  el("submit-btn").disabled = true;
  try {
    const res = await fetch("/api/jobs", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(req),
    });
    if (!res.ok) {
      const body = await res.json().catch(() => ({}));
      throw new Error(body.detail || `HTTP ${res.status}`);
    }
    const { job_id } = await res.json();
    addStudyCard(job_id, req.job_name);
    el("job-form").classList.add("hidden");
  } catch (e) {
    showError(`Couldn't start the job: ${e.message}`);
  } finally {
    el("submit-btn").disabled = false;
  }
});

