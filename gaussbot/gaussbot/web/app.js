(async () => {
  // Best-effort only -- the backend's own check is the definitive answer,
  // this just sets an informational tooltip so the button doesn't look
  // broken when there's obviously no credential configured.
  const avail = await fetch("/api/refine/available").then((r) => r.json()).catch(() => ({ available: false }));
  if (!avail.available) {
    ["reactant", "product"].forEach((slot) => {
      el(`${slot}-refine`).title = "Needs an Anthropic API credential configured on the server -- will show an error if unavailable.";
    });
  }
})();

function renderRefineResult(slot, resultId, body) {
  const resultEl = el(resultId);
  const mismatchColor = body.matches_description ? "" : ` style="color:var(--bad)"`;
  let html = `<p class="refine-note"${mismatchColor}>${body.notes}</p>`;

  if (body.pubchem_token) {
    html += `<div class="refine-suggestion">
      <span>PubChem structure available: ${body.pubchem_elements.join(", ")} (${body.pubchem_atom_count} atoms)</span>
      <button type="button" class="apply-btn" data-token="${body.pubchem_token}" data-elements='${JSON.stringify(body.pubchem_elements)}' data-count="${body.pubchem_atom_count}">Use this structure</button>
    </div>`;
  }
  if (body.smiles_token) {
    html += `<div class="refine-suggestion">
      <span>Suggested SMILES ${body.suggested_smiles}: ${body.smiles_elements.join(", ")} (${body.smiles_atom_count} atoms)</span>
      <button type="button" class="apply-btn" data-token="${body.smiles_token}" data-elements='${JSON.stringify(body.smiles_elements)}' data-count="${body.smiles_atom_count}">Use this structure</button>
    </div>`;
  }
  if (body.suggested_charge != null || body.suggested_multiplicity != null) {
    html += `<p class="refine-note">Suggested charge/multiplicity: ${body.suggested_charge ?? 0} / ${body.suggested_multiplicity ?? 1} -- adjust manually if this looks right, nothing is applied automatically.</p>`;
  }

  resultEl.innerHTML = html;

  resultEl.querySelectorAll(".apply-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      uploads[slot] = {
        token: btn.dataset.token,
        elements: JSON.parse(btn.dataset.elements),
        atom_count: parseInt(btn.dataset.count, 10),
      };
      const infoId = slot === "ts_guess" ? "ts-guess-info" : `${slot}-info`;
      const info = el(infoId);
      info.textContent = `OK: ${uploads[slot].atom_count} atoms (${uploads[slot].elements.join(", ")}) -- from AI-assisted refinement`;
      info.className = "file-info ok";
      renderGenecpElements();
      resultEl.querySelectorAll(".apply-btn").forEach((b) => (b.disabled = true));
      btn.textContent = "Applied";
    });
  });
}

async function handleRefine(slot, descId, resultId, buttonId) {
  const description = el(descId).value.trim();
  const resultEl = el(resultId);
  if (!description) {
    resultEl.innerHTML = '<p class="refine-note" style="color:var(--bad)">Enter a description first.</p>';
    return;
  }
  const upload = uploads[slot];
  if (!upload) {
    resultEl.innerHTML = '<p class="refine-note" style="color:var(--bad)">Load a structure (file or SMILES) above first.</p>';
    return;
  }

  const button = el(buttonId);
  button.disabled = true;
  resultEl.innerHTML = '<p class="refine-note">Asking Claude...</p>';

  const data = await postJSON("/api/refine", { token: upload.token, description });
  button.disabled = false;

  if (!data.ok) {
    resultEl.innerHTML = `<p class="refine-note" style="color:var(--bad)">${data.message}</p>`;
    return;
  }
  renderRefineResult(slot, resultId, data.body);
}

el("reactant-refine").addEventListener("click", () => handleRefine("reactant", "reactant-description", "reactant-refine-result", "reactant-refine"));
el("product-refine").addEventListener("click", () => handleRefine("product", "product-description", "product-refine-result", "product-refine"));

function unionElements() {
  const set = new Set();
  for (const key of ["reactant", "product", "ts_guess"]) {
    const u = uploads[key];
    if (u) u.elements.forEach((e) => set.add(e));
  }
  return Array.from(set).sort();
}

