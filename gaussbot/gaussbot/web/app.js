function updateStudyTypeVisibility() {
  const type = studyType();
  const mechanism = type === "mechanism";
  const tsSearch = type === "ts_search";
  const showProductTsGuess = mechanism || tsSearch;

  el("field-product").classList.toggle("hidden", !showProductTsGuess);
  el("field-ts-guess").classList.toggle("hidden", !showProductTsGuess);
  el("step-irc").classList.toggle("hidden", !mechanism);
  el("step-verification").classList.toggle("hidden", !mechanism);
  el("energy-units-field").classList.toggle("hidden", !mechanism);
  el("gcorr-block").classList.toggle("hidden", tsSearch);
  el("ts-recover-row").classList.toggle("hidden", !tsSearch);

  el("reactant-label").textContent = tsSearch ? "Reactant file (optional for TS search)" : mechanism ? "Reactant file" : "Structure file";
  el("product-label").textContent = tsSearch ? "Product file (optional for TS search)" : "Product file";
  el("ts-guess-summary-text").textContent = tsSearch
    ? "TS guess file (required unless both reactant and product are given)"
    : "Optional: TS guess file (auto-generated by interpolation if omitted)";
  el("energy-section-heading").textContent = mechanism ? "6. Energy report" : "6. Export options";

  if (!tsSearch) {
    el("reactant-log-warning").classList.add("hidden");
    el("product-log-warning").classList.add("hidden");
  } else {
    updateLogWarning("reactant");
    updateLogWarning("product");
  }
}

function updateLogWarning(slot) {
  if (studyType() !== "ts_search") return;
  const upload = uploads[slot];
  const filename = upload ? (el(`${slot}-file`).files[0] || {}).name || "" : "";
  const warning = el(`${slot}-log-warning`);
  warning.classList.toggle("hidden", !upload || filename.toLowerCase().endsWith(".log"));
}

document.querySelectorAll('input[name="study_type"]').forEach((r) =>
  r.addEventListener("change", updateStudyTypeVisibility)
);
updateStudyTypeVisibility();

// ---------------------------------------------------------------- uploads

function applyUploadResult(slot, infoId, data, errorPrefix) {
  const info = el(infoId);
  if (data.ok) {
    uploads[slot] = data.body;
    info.textContent = `OK: ${data.body.atom_count} atoms (${data.body.elements.join(", ")})`;
    info.className = "file-info ok";
  } else {
    uploads[slot] = null;
    info.textContent = `${errorPrefix}: ${data.message}`;
    info.className = "file-info err";
  }
  if (slot === "reactant" || slot === "product") updateLogWarning(slot);
  renderGenecpElements();
}

async function postJSON(url, body) {
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const errBody = await res.json().catch(() => ({}));
    return { ok: false, message: errBody.detail || `HTTP ${res.status}` };
  }
  return { ok: true, body: await res.json() };
}

async function handleFileUpload(inputId, infoId, slot) {
  const input = el(inputId);
  const info = el(infoId);
  const file = input.files[0];
  if (!file) {
    uploads[slot] = null;
    info.textContent = "";
    info.className = "file-info";
    renderGenecpElements();
    return;
  }
  info.textContent = "Reading...";
  info.className = "file-info";

  const form = new FormData();
  form.append("file", file);
  let data;
  try {
    const res = await fetch("/api/analyze", { method: "POST", body: form });
    if (!res.ok) {
      const errBody = await res.json().catch(() => ({}));
      data = { ok: false, message: errBody.detail || `HTTP ${res.status}` };
    } else {
      data = { ok: true, body: await res.json() };
    }
  } catch (e) {
    data = { ok: false, message: e.message };
  }
  applyUploadResult(slot, infoId, data, "Couldn't read this file");
}

async function handleSmilesLoad(smilesInputId, infoId, slot, buttonId) {
  const smiles = el(smilesInputId).value.trim();
  const info = el(infoId);
  if (!smiles) {
    info.textContent = "Enter a SMILES string first.";
    info.className = "file-info err";
    return;
  }
  const button = el(buttonId);
  button.disabled = true;
  info.textContent = "Embedding...";
  info.className = "file-info";

  // A SMILES load supersedes any file already chosen for this slot,
  // and vice versa -- whichever was done most recently wins.
  el(smilesInputId.replace("-smiles", "-file")).value = "";

  const data = await postJSON("/api/analyze_smiles", { smiles, label: slot });
  applyUploadResult(slot, infoId, data, `Couldn't embed ${smiles}`);
  button.disabled = false;
}

